#!/usr/bin/env python3
"""Compare ARC0 path manifests with APK/IPA central directories.

This compares names and declared ZIP sizes only. It never extracts or hashes
the package payloads, and the generated report intentionally omits paths.
"""

from __future__ import annotations

import argparse
import json
import posixpath
import sys
from collections import Counter
from pathlib import Path
from zipfile import ZipFile


def normalized_mobile_paths(package: Path, kind: str) -> tuple[set[str], dict]:
    with ZipFile(package) as archive:
        entries = archive.infolist()

    if kind == "apk":
        prefix = "assets/"
        selected = [entry for entry in entries if entry.filename.startswith(prefix)]
    else:
        prefix = "Payload/yw1_rom.app/data/"
        selected = [entry for entry in entries if entry.filename.startswith(prefix)]

    paths = {posixpath.normpath(entry.filename[len(prefix):]) for entry in selected}
    extensions = Counter(Path(path).suffix.lower() or "<none>" for path in paths)
    return paths, {
        "package": str(package),
        "zip_entries": len(entries),
        "selected_entries": len(selected),
        "normalized_paths": len(paths),
        "selected_declared_bytes": sum(entry.file_size for entry in selected),
        "extensions": dict(sorted(extensions.items())),
    }


def load_arc0(path: Path) -> tuple[set[str], dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    paths = {posixpath.normpath(item["path"]) for item in data["files"]}
    extensions = Counter(Path(path).suffix.lower() or "<none>" for path in paths)
    return paths, {
        "manifest": str(path),
        "archive_size": data["archive_size"],
        "directory_count": data["directory_count"],
        "file_count": data["file_count"],
        "payload_bytes": data["payload_bytes"],
        "compression": {
            name: value["method"] for name, value in data["compression"].items()
        },
        "extensions": dict(sorted(extensions.items())),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--arc0",
        action="append",
        required=True,
        metavar="LABEL=MANIFEST.json",
        help="ARC0 manifest generated by inspect_arc0.py; repeat for each archive",
    )
    parser.add_argument("--apk", type=Path, required=True)
    parser.add_argument("--ipa", type=Path, required=True)
    parser.add_argument("--json-out", type=Path)
    args = parser.parse_args()

    manifests: dict[str, tuple[set[str], dict]] = {}
    for item in args.arc0:
        if "=" not in item:
            parser.error(f"--arc0 must use LABEL=PATH, got {item!r}")
        label, raw_path = item.split("=", 1)
        if not label or not raw_path:
            parser.error(f"--arc0 must use LABEL=PATH, got {item!r}")
        manifests[label] = load_arc0(Path(raw_path))

    apk_paths, apk_info = normalized_mobile_paths(args.apk, "apk")
    ipa_paths, ipa_info = normalized_mobile_paths(args.ipa, "ipa")
    mobile_shared = apk_paths & ipa_paths

    report = {
        "comparison": "path names and declared sizes only",
        "mobile": {
            "apk": apk_info,
            "ipa": ipa_info,
            "apk_ipa_shared_paths": len(mobile_shared),
            "apk_only_paths": len(apk_paths - ipa_paths),
            "ipa_only_paths": len(ipa_paths - apk_paths),
        },
        "arc0": {},
    }

    for label, (arc_paths, arc_info) in manifests.items():
        report["arc0"][label] = {
            **arc_info,
            "apk_exact_path_matches": len(arc_paths & apk_paths),
            "ipa_exact_path_matches": len(arc_paths & ipa_paths),
            "mobile_shared_exact_path_matches": len(arc_paths & mobile_shared),
        }

    if args.json_out:
        args.json_out.parent.mkdir(parents=True, exist_ok=True)
        args.json_out.write_text(
            json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )

    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
